export function getAllEvents() {
  return EVENTS;
}

export function getEventBySlug(slug: string) {
  return EVENTS.find((event) => event.slug === slug) ?? null;
}

export function getEventById(id: string) {
  return EVENTS.find((event) => event.id === id) ?? null;
}

export function getEventsByCity(citySlug: string) {
  return EVENTS.filter((event) => event.citySlug === citySlug);
}

export function getHostProfile(slug: string) {
  const events = EVENTS.filter((event) => event.host.slug === slug);
  if (!events.length) return null;
  return { host: events[0].host, events };
}
