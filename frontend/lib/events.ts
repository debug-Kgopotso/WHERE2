import type { Category, EventItem, Host } from "@/lib/types";

const photo = (id: string) =>
  `https://images.unsplash.com/${id}?auto=format&fit=crop&w=2000&q=80`;

type Draft = {
  id: string;
  title: string;
  dek: string;
  description: string;
  category: Category;
  image: string;
  extra?: string[];
  venue: string;
  address: string;
  city: string;
  lat: number;
  lng: number;
  start: string;
  end: string;
  priceLabel: string;
  priceValue: number;
  age: string;
  featured?: boolean;
  host: string;
  hostBio: string;
  area: string;
};

function slugify(value: string) {
  return value
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

function make(draft: Draft): EventItem {
  const host: Host = {
    slug: slugify(draft.host),
    name: draft.host,
    bio: draft.hostBio,
    neighborhood: draft.area,
  };
  return {
    id: draft.id,
    slug: draft.id,
    title: draft.title,
    dek: draft.dek,
    description: draft.description,
    category: draft.category,
    images: [photo(draft.image), ...(draft.extra ?? []).map(photo)],
    venue: draft.venue,
    address: draft.address,
    citySlug: draft.city,
    lat: draft.lat,
    lng: draft.lng,
    startAt: draft.start,
    endAt: draft.end,
    priceLabel: draft.priceLabel,
    priceValue: draft.priceValue,
    externalLink: `https://example.com/where2/${draft.id}`,
    age: draft.age,
    isFeatured: Boolean(draft.featured),
    host,
  };
}

